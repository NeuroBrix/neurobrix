#!/usr/bin/env python3
"""docs/reference/benchmarks.md from the measurements already recorded — the gates' rows, no GPU (supervisor 2026-10-15 18:00).

Every rc 0 row of the given rows files (`regression_matrix.py run` rows: wall_s, load_s, exec_s, ttft_s, tok_s, tokens,
date, engine, request) is one measurement of (model, mode, machine, card class). The card class is the matrix
directory's (`matrix_16g`, `matrix_32g`, ...) or, for a directory that names none, the card's (`--card-class 0=16g,...`,
the machine's own table). Duplicates — a row carried by record into later gates — count once (same model, mode, class,
engine and wall time; it takes the carrying gate's date, so its earliest date is kept). Per (model, mode, class): the latest measurement with its request and engine commit, and the evolution
(count, first and latest wall time, fastest — at the latest measurement's request only). `--plans` names the Prism plan listing (plan_identical.txt): a model whose
plan is identical across the classes is marked so (one plan, two cards).

    benchmarks_md.py --machine "dell V100" --card-class 0=16g,1=16g,2=32g,3=32g --plans DIR --out FILE ROWS...
    benchmarks_md.py --machine "Mac ..." --card-class 0=18g --append --out FILE ROWS...   (the second machine's section)
Refused by name when no row is read. A gate measurement is not a benchmark: written at the top of the file.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path


def card_class(rows_file: Path, gpu, table) -> str:
    for part in rows_file.parts[::-1]:
        m = re.match(r"matrix_(\d+g)", part)
        if m:
            return m.group(1)
    if str(gpu) in table:
        return table[str(gpu)]
    raise SystemExit(f"REFUSED: {rows_file}: no matrix_<class> directory and card {gpu} is not in --card-class")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--machine", required=True)
    ap.add_argument("--card-class", required=True)
    ap.add_argument("--plans", default=None)
    ap.add_argument("--out", required=True)
    ap.add_argument("--append", action="store_true",
                    help="append this machine's section to an existing file (the second machine's data), header kept")
    ap.add_argument("rows", nargs="+")
    a = ap.parse_args(argv)
    table = dict(kv.split("=") for kv in a.card_class.split(","))
    identical = set()
    if a.plans:
        identical = {l.split()[0] for l in (Path(a.plans) / "plan_identical.txt").read_text().splitlines() if l.strip()}
    meas = {}
    for f in a.rows:
        f = Path(f)
        for line in f.read_text().splitlines():
            try:
                r = json.loads(line)
            except ValueError:
                continue
            if r.get("rc") != 0 or not r.get("wall_s"):
                continue
            cls = card_class(f, r.get("gpu"), table)
            # a row carried by record into a later gate keeps its engine and its wall time and takes that gate's date:
            # one measurement, counted once, at its earliest date
            key = (r["model"], r["mode"], cls, r.get("engine", ""), r.get("wall_s"))
            if key not in meas or r.get("date", "") < meas[key].get("date", ""):
                meas[key] = r
    if not meas:
        print("REFUSED: no rc 0 row with a wall time in the inputs", file=sys.stderr)
        return 2
    by = {}
    for (m, mode, cls, _e, _w), r in meas.items():
        by.setdefault((m, mode, cls), []).append(r)
    head = [f"# Benchmarks — gate measurements, not a benchmark",
           "",
           "Every figure below is a gate cell's own measurement: the gate request (the model's floor, certified-only), one run,",
           "on a rack shared by other cells. It says how long a model takes at that request on that engine commit; it is not a",
           "controlled benchmark. Generated by `tools/benchmarks_md.py` from the gates' rows; each figure carries its request and",
           "its engine commit.",
           ""]
    out = [f"## {a.machine}",
           "",
           "| model | mode | card | plan | latest (date, engine) | wall s | load s | exec s | tok/s | runs at this request | first wall s | fastest s | request |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for (m, mode, cls) in sorted(by):
        rs = sorted(by[(m, mode, cls)], key=lambda r: r.get("date", ""))
        last = rs[-1]
        # the evolution compares like with like: the runs at the latest request only
        rs = [r for r in rs if r.get("request") == last.get("request")]
        first = rs[0]
        fastest = min(r["wall_s"] for r in rs)
        req = " ".join(str(x) for x in (last.get("request") or []))
        req = re.sub(r"/\S+/", "", req)[:90]
        tok = f"{last['tok_s']:.2f}" if isinstance(last.get("tok_s"), (int, float)) else ""
        fmt = lambda v: f"{v:.1f}" if isinstance(v, (int, float)) else ""
        plan = "one plan, two cards" if m in identical else "per card"
        out.append(f"| {m} | {mode} | {cls} | {plan} | {last.get('date','')[:10]}, {str(last.get('engine',''))[:9]} | "
                   f"{fmt(last.get('wall_s'))} | {fmt(last.get('load_s'))} | {fmt(last.get('exec_s'))} | {tok} | {len(rs)} | "
                   f"{fmt(first.get('wall_s'))} | {fmt(fastest)} | `{req}` |")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    if a.append:
        if not Path(a.out).is_file():
            print(f"REFUSED: --append and {a.out} does not exist", file=sys.stderr)
            return 2
        with open(a.out, "a") as f:
            f.write("\n" + "\n".join(out) + "\n")
    else:
        Path(a.out).write_text("\n".join(head + out) + "\n")
    print(f"{a.out}: {len(by)} (model, mode, card) lines from {len(meas)} measurements in {len(a.rows)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
